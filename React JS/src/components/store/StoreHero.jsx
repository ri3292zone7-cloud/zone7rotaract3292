export default function StoreHero() {
  const root = useRef(null);
  const copyRef = useRef(null);
  const hintRef = useRef(null);
  const [index, setIndex] = useState(0);
  const [live, setLive] = useState(false);
  const rot = useRef({ y: 0, vel: 0, dragging: false });

  const scene = SCENES[index];

  const go = useCallback((dir) => {
    setIndex((i) => mod(i + dir, SCENES.length));
    if (hintRef.current) hintRef.current.classList.add('hide');
  }, []);

  const interact = useCallback(() => {
    if (hintRef.current) hintRef.current.classList.add('hide');
  }, []);

  // mount the canvas only while the hero is on screen
  useEffect(() => {
    const el = root.current;
    if (!el) return;
    const io = new IntersectionObserver(
      ([en]) => {
        if (en.isIntersecting) setLive(true);
      },
      { threshold: 0.05 }
    );
    io.observe(el);
    return () => io.disconnect();
  }, []);

  // slow auto-advance while on screen
  useEffect(() => {
    const el = root.current;
    if (!el) return;
    const io = new IntersectionObserver(([en]) => (el.__visible = en.isIntersecting), { threshold: 0.4 });
    io.observe(el);
    const timer = setInterval(() => {
      if (el.__visible && !document.hidden) setIndex((i) => (i + 1) % SCENES.length);
    }, 9000);
    return () => {
      io.disconnect();
      clearInterval(timer);
    };
  }, []);

  useEffect(() => {
    const onKey = (e) => {
      if (e.key === 'ArrowRight') go(1);
      if (e.key === 'ArrowLeft') go(-1);
    };
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [go]);

  const goSection = () => {
    const target = document.querySelector(scene.href);
    if (target) target.scrollIntoView({ behavior: 'smooth' });
  };

  return (
    <section className="sh-hero" ref={root} id="top">
      <div className="sh-bg"></div>

      <div className="wrap sh-wrap">
        <div className="sh-copy" ref={copyRef}>
          <Eyebrow dark>Rotaract District 3292 · Official Merch</Eyebrow>
          <div className="sh-panels">
            {SCENES.map((s, i) => (
              <div key={s.id} className={`sh-panel ${i === index ? 'on' : ''}`} aria-hidden={i !== index}>
                <span className="sh-kicker" style={{ color: s.accent }}>
                  {s.kicker}
                </span>
                <h1 className="sh-h1">{s.title}</h1>
                <p className="sh-sub">{s.sub}</p>
                <div className="sh-actions">
                  <span className="sh-price">{s.price}</span>
                  <a
                    className="btn btn-primary"
                    href={s.href}
                    onClick={(e) => {
                      e.preventDefault();
                      goSection();
                    }}
                  >
                    {s.cta} →
                  </a>
                </div>
              </div>
            ))}
          </div>
        </div>

        <div className="sh-stage">
          <div className="sh-frame">
            {live ? (
              <Canvas
                camera={{ position: [0, 0.5, 5.0], fov: 34 }}
                dpr={[1, 1.5]}
                gl={{ antialias: true, alpha: true, powerPreference: 'high-performance' }}
                style={{ width: '100%', height: '100%' }}
              >
                <Showcase index={index} rot={rot} onSwipe={go} onInteract={interact} />
              </Canvas>
            ) : (
              <div className="sh-boot" aria-hidden="true">
                <span>Z7</span>
              </div>
            )}
          </div>
          <span className="sh-spec" key={scene.id}>
            {scene.spec}
          </span>
        </div>
      </div>

      <div className="sh-bottom">
        <button type="button" className="sh-arrow" aria-label="Previous drop" onClick={() => go(-1)}>
          ←
        </button>
        <div className="sh-dots">
          {SCENES.map((s, i) => (
            <button
              key={s.id}
              type="button"
              className={`sh-dot ${i === index ? 'on' : ''}`}
              aria-label={s.kicker}
              onClick={() => {
                setIndex(i);
                interact();
              }}
            />
          ))}
        </div>
        <span className="sh-count">
          0{index + 1} / 0{SCENES.length}
        </span>
        <button type="button" className="sh-arrow" aria-label="Next drop" onClick={() => go(1)}>
          →
        </button>
      </div>

      <div className="sh-hint" ref={hintRef} aria-hidden="true">
        ✦ drag to rotate · swipe to switch
      </div>

      <div className="hero-scroll-hint" aria-hidden="true">
        <span className="mouse"><i></i></span> scroll — the drop keeps going
      </div>
    </section>
  );
}
