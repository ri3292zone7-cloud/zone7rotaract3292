/*
 * Procedural studio environment — reflections for every material without a
 * single network request. RoomEnvironment is generated by three.js itself.
 */
function StudioEnv() {
  const gl = useThree((s) => s.gl);
  const scene = useThree((s) => s.scene);

  useEffect(() => {
    const pmrem = new THREE.PMREMGenerator(gl);
    const envTex = pmrem.fromScene(new RoomEnvironment(), 0.04).texture;
    scene.environment = envTex;
    scene.environmentIntensity = 0.6;
    return () => {
      scene.environment = null;
      envTex.dispose();
      pmrem.dispose();
    };
  }, [gl, scene]);

  return null;
}

/*
 * Fits the product inside the frame at every aspect ratio — wide desktop
 * frames show the product large; narrow mobile frames zoom the camera out
 * so sleeves and brims never clip the edges.
 */
function ResponsiveZoom() {
  const camera = useThree((s) => s.camera);
  const size = useThree((s) => s.size);

  useEffect(() => {
    const aspect = size.width / size.height;
    camera.zoom = aspect < 0.85 ? 0.58 : aspect < 1.15 ? 0.8 : 1;
    camera.updateProjectionMatrix();
  }, [camera, size]);

  return null;
}

function ShowcaseRig({ rot, children }) {
  const group = useRef(null);

  useFrame((_, delta) => {
    const g = group.current;
    if (!g) return;
    const r = rot.current;
    if (r.dragging) {
      g.rotation.y = r.y;
      return;
    }
    // momentum decay → idle auto-rotate
    r.y += r.vel;
    r.vel *= Math.pow(0.002, delta);
    if (Math.abs(r.vel) < 0.001) r.y += delta * 0.26;
    g.rotation.y = r.y;
  });

  return <group ref={group}>{children}</group>;
}

function StagePointer({ rot, onSwipe, onInteract }) {
  const gl = useThree((s) => s.gl);

  useEffect(() => {
    const el = gl.domElement;
    el.style.touchAction = 'pan-y';
    el.style.cursor = 'grab';
    const r = rot.current;
    let pointerId = null;
    let startX = 0;
    let startY = 0;
    let lastX = 0;

    const down = (e) => {
      if (e.pointerType === 'mouse' && e.button !== 0) return;
      pointerId = e.pointerId;
      startX = lastX = e.clientX;
      startY = e.clientY;
      r.dragging = true;
      r.vel = 0;
      el.setPointerCapture(e.pointerId);
      el.style.cursor = 'grabbing';
      onInteract();
    };

    const move = (e) => {
      if (!r.dragging || e.pointerId !== pointerId) return;
      const dx = e.clientX - lastX;
      lastX = e.clientX;
      r.y += dx * 0.0062;
      r.vel = dx * 0.0062;
    };

    const up = (e) => {
      if (e.pointerId !== pointerId) return;
      pointerId = null;
      r.dragging = false;
      el.style.cursor = 'grab';
      const dx = lastX - startX;
      const dy = e.clientY - startY;
      if (Math.abs(dx) > 64 && Math.abs(dy) < 90) onSwipe(dx > 0 ? -1 : 1);
      onInteract();
    };

    el.addEventListener('pointerdown', down);
    el.addEventListener('pointermove', move);
    el.addEventListener('pointerup', up);
    el.addEventListener('pointercancel', up);
    return () => {
      el.removeEventListener('pointerdown', down);
      el.removeEventListener('pointermove', move);
      el.removeEventListener('pointerup', up);
      el.removeEventListener('pointercancel', up);
    };
  }, [gl, rot, onSwipe, onInteract]);

  return null;
}

